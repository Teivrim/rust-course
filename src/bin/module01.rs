//! ============================================================================
//!
//! ЧАСТЬ 1.1 — ТЕОРИЯ
//! ─────────────────────────────────────────────────────────────────────────────
//! В C++ ты владеешь памятью через `new`/`delete` и неявно — через RAII.
//! Rust переносит RAII из «рекомендации» в **правило языка**: у каждого
//! значения ровно один владелец, и компилятор сам освобождает его.
//!
//! ТРИ ПРАВИЛА ВЛАДЕНИЯ (это весь язык в одной строчке):
//!
//!   1. У каждого значения в каждый момент есть ОДИН владелец.
//!   2. Когда владелец уходит из области видимости, значение уничтожается.
//!   3. Владение может быть передано (move) — тогда у прежнего владельца
//!      значения больше нет.
//!
//! ЧТО ЭТО ЗНАЧИТ НА ПРАКТИКЕ (сравни с C++):
//!
//!   C++:                              Rust:
//!   auto a = std::make_unique<Foo>();  let a = Foo::new();        // владение
//!   auto b = std::move(a);             let b = a;                 // move
//!   // a теперь nullptr, но ~Foo()      // у a теперь нет значения;
//!   // вызовется И у b, И у a          // Drop вызовется РОВНО ОДИН раз — у b
//!   // (в double-delete/undefined)     // (двойного освобождения не бывает)
//!
//! ВАЖНЕЙШЕЕ ОТЛИЧИЕ ОТ `std::move`:
//!   `std::move` в C++ — это просто `static_cast<T&&>`, т.е. **не делает
//!   ничего**. Дальше срабатывает конструктор перемещения, а из источника
//!   переменная НЕ обнуляется. Отсюда ваши double-free и use-after-move.
//!   В Rust `let b = a;` — это перемещение дескриптора, и компилятор
//!   **запрещает** читать `a` после. Ошибка, а не "ой".
//!
//! СРАВНИ С C++ ДЛЯ КОПИРУЕМЫХ ТИПОВ:
//!   `int n1 = 42; int n2 = n1;` в Rust — это `Copy`: обе переменные живы,
//!   потому что копировать целое бесплатно и незаметно. Rust применяет
//!   `Copy` только к типам, где копирование тривиально и дешево.
//!   У `String`/`Vec` копирование дорогое, поэтому `Copy` не реализован —
//!   только move.
//!
//! ГДЕ ЛЕЖИТ ДАННЫЕ: `String` и `Vec<T>` — дескрипторы (ptr, len, cap),
//! это три слова, лежат на СТЕКЕ. Данные — на КУЧЕ. `Copy`-типы целиком
//! лежат на стеке/в регистрах. Rust не «оптимизирует это», он просто
//! различает дешёвое и дорогое на уровне типов.
//!
//! ЧАСТЬ 1.2 — ПРИМЕР
//! ─────────────────────────────────────────────────────────────────────────────
//! Смотри на `part_1_2()`: move, копирование целого, move `Vec`, порядок
//! вызовов `Drop` (обратный порядку объявления) и частичный move.
//! Раскомментируй помеченные строки — увидишь реальные диагностики
//! компилятора. Это самая полезная привычка в обучении Rust.

