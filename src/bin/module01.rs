fn part_1_1() {
    harness::part("1.1", "ПРИМЕР: move, Copy, use-after-move");

    // --- MOVE: дешёвая структура, дорогие данные -----------------------------
    let s1 = String::from("vertex buffer");
    println!("  s1.as_ptr() = {:p}, len = {}", s1.as_ptr(), s1.len());

    let s2 = s1; // ← MOVE. Не копирование!
    println!("  s2.as_ptr() = {:p}, len = {}", s2.as_ptr(), s2.len());
    println!("  ^ указатели ОДИНАКОВЫЕ: это одни и те же данные, владение перешло");

    // println!("  {s1}");  // ⛔ E0382: borrow of moved value: `s1`

    // --- COPY: целое копируется, обе переменные живут -----------------------
    let n1: u32 = 42;
    let n2 = n1; // Copy
    println!("\n  Copy: n1 = {n1}, n2 = {n2}   (обе живы, это просто число)");

    // --- Vec<T> — move, данные НЕ дублируются -------------------------------
    let v1 = vec![1.0f32, 2.0, 3.0, 4.0];
    let v2 = v1; // move
    println!("  Vec: v2 = {v2:?}, v1 не существует, копии в куче нет");

    // --- Перемещение невидимо в вызовах функций ------------------------------
    let name = String::from("cube");
    takes_ownership(name); // name съеден
    // println!("{name}");  // ⛔ E0382 — и это правильно: нельзя использовать

    // --- Возврат значения = перемещение обратно ------------------------------
    let owner = produce();
    println!("  produce() вернул: {owner} (владение снова у нас)");

    // --- Явное клонирование, когда копия реально нужна -----------------------
    let a = String::from("shader.glsl");
    let b = a.clone(); // clone: новая память, теперь две независимые строки
    println!("  clone: a={a:?} b={b:?} — разные указатели: {:p} vs {:p}", a.as_ptr(), b.as_ptr());
}

