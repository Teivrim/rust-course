fn part_14_1() {
    harness::part("14.1", "ПРИМЕР: спецификаторы, повторения, гигиена");

    // --- Простой макрос ------------------------------------------------------
    println!("  double!(21) = {}", double!(21));
    let a = 3;
    let b = 4;
    println!("  double!(a) + b = {} (expr жадный, скобки не нужны)", double!(a) + b);
    // ⚠ double!(a; b) — уже другая история: `;` разделит вызов и код.
    println!("  double!((1 + 2) * 3) = {}", double!((1 + 2) * 3));

    // --- Повторения ---------------------------------------------------------
    println!("  max_of!(1, 9, 3)     = {}", max_of!(1, 9, 3));
    println!("  max_of!(single())   = {}", max_of!(single_value()));
    println!("  max_of!(1, 2, 3,)    = {} (висячая запятая)", max_of!(1, 2, 3,));
    println!("  max_of!(1 + 2 * 3, 4) = {} (expr с запятыми внутри скобок)", max_of!(1 + 2 * 3, 4));
    // max_of!();  // ⛔ `$first` обязателен — это хорошо, ошибка внятная

    // --- Считаем токены -----------------------------------------------------
    let n = count_idents!(a, b, c, d, e);
    assert_eq!(n, 5);
    println!("  count_idents!(a,b,c,d,e) = {n} (длина среза, а не ${{count}} — он нестабилен)");
    assert_eq!(count_idents!(), 0);
    println!("  count_idents!() = 0 — повторитель * допускает ноль");

    // --- Макрос в несколько выражений ---------------------------------------
    let (v, ns) = timed!(|| 6 * 7);
    println!("  timed(|| 6*7) = {v} за {ns} нс");

    // --- Спецификатор ty -----------------------------------------------------
    let x: u8 = 7;
    let y = expect_ty!(x, u8);
    println!("  expect_ty!(x, u8) = {y} (проверку сделал компилятор, не я)");
    // let _ = expect_ty!(x, u16);  // ⛔ E0308 mismatched types

    // --- Генерация структуры и Default --------------------------------------
    let d = Config::default();
    println!("  Config::default() = {}x{} vsync={}", d.width, d.height, d.vsync);
    let mut c = Config { width: 800, ..Config::default() };
    c.height = 600;
    println!("  после `..Config::default()`: {}x{}", c.width, c.height);

    // --- Гигиена: макрос вводит свои переменные ------------------------------
    let x = 100;
    println!("  hygiene: with_local!(x) = {} (макрос завёл СВОИ x=2, y=3)", hygiene::with_local_x(x));
    assert_eq!(x, 100, "наша x не тронута");

    // --- X-макрос ------------------------------------------------------------
    // ⚠ Функция `name() -> bool` генерируется для КАЖДОГО имени в списке.
    //   Поэтому «несуществующее» расширение проверяем через `has`,
    //   а не через сгенерированную функцию: её для VK_EXT_nope просто нет.
    println!("\n  поддерживается расширений: {}", extensions::SUPPORTED.len());
    println!("  есть VK_KHR_swapchain: {}", extensions::has("VK_KHR_swapchain"));
    println!("  есть VK_EXT_nope:     {}", extensions::has("VK_EXT_nope"));
    assert!(extensions::VK_KHR_surface());
    // extensions::VK_EXT_nope();   // ⛔ E0425: функции нет — компилятор нашёл опечатку
    println!("  один список дал и строки, и функции, и проверку");
    println!("    ⚠ Опечатку в ИМЕНИ ловит компилятор. Опечатку в строке — никто.");

    // --- Сгенерированная структура ------------------------------------------
    println!("  Color::from_hex(0xFF8000) = {:?}", Color::from_hex(0xFF8000));
}

