// МАКРОСЫ — объявлены ДО использования. Это не стиль, а требование языка.
// ═════════════════════════════════════════════════════════════════════════════

/// Минимальный макрос: один аргумент-выражение, один результат.
macro_rules! double {
    ($x:expr) => {
        $x * 2
    };
}

/// Повторение с разделителем. Транскриптер повторяет `$x` столько же раз.
/// ⚠ ПЕРВЫЙ ЭЛЕМЕНТ ПРИНИМАЕМ ОТДЕЛЬНО: `$($x),+` не позволяет
/// обратиться к «первому», а нужен начальный аккумулятор.
macro_rules! max_of {
    ($first:expr $(, $rest:expr)* $(,)?) => {{
        #[allow(unused_mut)] // при единственном аргументе `m` не меняется
        let mut m = $first;
        $(
            if $rest > m {
                m = $rest;
            }
        )*
        m
    }};
}

/// Макрос, раскрывающийся в НЕСКОЛЬКО выражений. Результат обязан быть
/// в скобках, иначе `a + timed!(...)` склеится неверно.
macro_rules! timed {
    ($body:expr) => {{
        let start = std::time::Instant::now();
        // ⚠ Фрагмент `expr` подставляется КАК ЕСТЬ. Чтобы его выполнить,
        //   нужны скобки: `($body)()`. Без них `r` станет самим замыканием.
        let r = ($body)();
        (r, start.elapsed().as_nanos())
    }};
}

/// Считает токены, возвращая длину среза. Ровно то, ради чего люди
/// пишут макросы: компилятор делает работу за тебя.
macro_rules! count_idents {
    ($($x:ident),* $(,)?) => {{
        // Явная аннотация типа обязательна: при ПУСТОМ списке массив
        // не имеет ни одного элемента, и вывести тип неоткуда.
        let arr: &[&str] = &[$(stringify!($x)),*];
        arr.len()
    }};
}

/// Тип и значение в одном аргументе. Показывает спецификаторы `ty`/`expr`
/// рядом: полезно для проверок «это действительно тот тип».
macro_rules! expect_ty {
    ($v:expr, $t:ty) => {{
        let _type_check: $t = $v;
        _type_check
    }};
}

/// Гигиеничность: внутренний `x` не сливается с внешним `x`.
mod hygiene {
    macro_rules! with_local {
        ($e:expr) => {{
            let x = 2; // этот x принадлежит макросу
            let y = 3; // и этот тоже
            $e * x * y
        }};
    }

    pub fn with_local_x(x: i32) -> i32 {
        with_local!(x)
    }
}

/// X-макрос: один список порождает данные, функции и проверки.
mod extensions {
    macro_rules! extensions {
        ($($name:ident),* $(,)?) => {
            /// Строки для передачи в API.
            pub const SUPPORTED: &[&str] = &[$(stringify!($name)),*];

            $(
                #[doc = concat!("Есть ли расширение ", stringify!($name))]
                pub fn $name() -> bool { true }
            )*

            /// Проверка по имени.
            pub fn has(name: &str) -> bool {
                SUPPORTED.contains(&name)
            }
        };
    }

    extensions! {
        VK_KHR_surface,
        VK_KHR_swapchain,
        VK_EXT_debug_utils,
    }
}

/// Макрос, генерирующий структуру + конструктор + Display.
macro_rules! color_struct {
    ($name:ident, $r:literal, $g:literal, $b:literal) => {
        struct $name {
            r: u8,
            g: u8,
            b: u8,
        }

        impl $name {
            const fn from_hex(hex: u32) -> Self {
                $name {
                    r: ((hex >> 16) & 0xFF) as u8,
                    g: ((hex >> 8) & 0xFF) as u8,
                    b: (hex & 0xFF) as u8,
                }
            }
        }

        impl std::fmt::Debug for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                write!(f, concat!(stringify!($name), "(#{:02X}{:02X}{:02X})"), self.r, self.g, self.b)
            }
        }
    };
}

color_struct!(Color, 255, 128, 0);

/// Макрос, генерирующий структуру с дефолтами из списка полей.
macro_rules! struct_fields {
    ($( $name:ident : $ty:ty = $default:expr ),* $(,)?) => {
        struct Config {
            $( $name: $ty, )*
        }
        impl Default for Config {
            fn default() -> Self {
                Config { $( $name: $default, )* }
            }
        }
    };
}

struct_fields! {
    width: u32 = 1920,
    height: u32 = 1080,
    vsync: bool = true,
}

