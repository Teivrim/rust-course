//! ============================================================================
//! МОДУЛЬ 14 — МАКРОСЫ
//! ============================================================================
//!
//! ЧАСТЬ 14.1 — ТЕОРИЯ: анатомия macro_rules!
//! ─────────────────────────────────────────────────────────────────────────────
//! Макрос в Rust — это ПРЕДОБРАБОТКА ТОКЕНОВ, а не вызов функции.
//! Он подставляет код ДО компиляции. Поэтому:
//!   * аргументы не типизируются (принимаются токены);
//!   * результат не типизируется на границе макроса;
//!   * гигиеничность: имена переменных из макроса не сливаются с
//!     именами вызывающего (кроме переданных явно).
//!
//! АНАТОМИЯ:
//!
//! ```ignore
//! macro_rules! имя {
//!     (pat => pat, pat)   { transcriber }   // matcher => transcriber
//! }
//! ```
//!
//! MATCHER — шаблон того, что принимаем. Спецификаторы фрагментов:
//!
//!   expr        выражение          ident   идентификатор
//!   ty          тип                pat     образец (паттерн)
//!   path        путь (a::b::C)     tt      один токен дерева
//!   block       блок { .. }        stmt    statement
//!   meta        атрибут             vis     видимость (pub/priv)
//!   literal     литерал            lifetime 'a
//!
//! ⚠ ГЛАВНОЕ ПРАВИЛО РАЗБОРА ФРАГМЕНТОВ: компилятор ищет БЛИЖАЙШИЙ
//!   допустимый парсер. В `println!("{}", x)` строка разбирается как
//!   `literal`, а не `expr`. Порядок регистрации спецификаторов влияет
//!   на то, что «съест» каждый из них.
//!
//! ТРАНСКРИПТЕР — код, который подставляется. В нём:
//!   * `$name` — подставить захваченный фрагмент;
//!   * `$( ... )*` — повторение (ноль или больше);
//!   * `$( ... ),*` — повторение с разделителем (запятая ПОСЛЕДНИМ);
//!   * `$( ... )?` — опциональный фрагмент (ноль или один).
//!
//! ЧЕСТЫЕ ГРАБЛИ:
//!   * `macro_rules!` разворачиваются В ПОРЯДКЕ ОБЪЯВЛЕНИЯ, сверху вниз.
//!     Макрос нельзя вызвать раньше, чем он объявлен — в отличие от
//!     функции. Это отличает Rust от C++ и Lisp.
//!   * Первый элемент нельзя вытащить из `$($x),+` напрямую: `$x`
//!     вне повторения не связан. Решение — принять первый отдельно
//!     (`$first:expr $(, $rest:expr)*`). Именно так сделан `max_of!`.
//!   * `expr` и `stmt` запрещены внутри повторений: Rust не может
//!     надёжно их разделить. Бери `tt` или конкретный фрагмент.
//!   * `${count($x)}` (metavariable expressions) до сих пор НЕСТАБИЛЬНО.
//!     Не планируй на этом код. Считай через длину среза.
//!   * Пустой повторитель `*` даёт ноль элементов — транскриптер не
//!     должен требовать наличия переменной из этого повторения.
//!
//! СРАВНИ С C++:
//!   #define            — подстановка токенов без гигиены, ломает код;
//!   constexpr-функция  — почти всегда лучше макроса.
//!   В Rust порядок такой же: сначала fn/const fn, потом макрос.
//!   Исключения, где макрос лучше: сгенерировать 20 однотипных
//!   структур или impl'ов, которые компилятор иначе не проверит.

