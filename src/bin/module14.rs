// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТЬ 14.2 — ТЕОРИЯ: экспорт и кодогенерация
// ─────────────────────────────────────────────────────────────────────────────
//
// ЭКСПОРТ. `macro_rules!` виден только ПОСЛЕ объявления в том же крейте.
// Чтобы отдать наружу:
//
// ```ignore
// #[macro_export]              // кладёт в корень крейта: crate::my_macro!
// macro_rules! my_macro { ... }
// ```
//
// ⚠ ВНУТРИ самого крейта после `#[macro_export]` макрос доступен ТОЛЬКО
//   как `crate::my_macro!` или через `use crate::my_macro;`
//   (просто по имени не работает). Это главный источник путаницы, и
//   в этом курсе обойдён тем, что макросы `not_yet!` и `bitflags!`
//   импортируются через `use curriculum::not_yet;`.
//
// ⚠ ЛОКАЛЬНЫЕ МАКРОСЫ (`macro_rules!` внутри `fn` или `mod`) нельзя
//   экспортировать: `#[macro_export]` работает только на верхнем уровне.
//
// КОДОГЕНЕРАЦИЯ В build.rs. x-макрос хорош, пока список маленький.
// Как только он перестаёт читаться — генерируй обычный `.rs` в OUT_DIR
// и подключай через `include!`:
//
// ```ignore
// // build.rs
// let dest = PathBuf::from(env::var("OUT_DIR")?).join("extensions.rs");
// fs::write(&dest, "pub const N: usize = 42;\n")?;
// println!("cargo:rerun-if-changed=build.rs");
//
// // src/lib.rs
// include!(concat!(env!("OUT_DIR"), "/extensions.rs"));
// ```
//
// ПОЧЕМУ ЭТО ЛУЧШЕ X-МАКРОСА ДЛЯ БОЛЬШИХ СПИСКОВ:
//   * сгенерированный файл можно ОТКРЫТЬ и прочитать;
//   * ошибки указывают на строку файла, а не на строку макроса;
//   * `cargo expand` (которого тут нет) не нужен.
//
// КОГДА ЧТО ИСПОЛЬЗОВАТЬ — таблица решений:
//
//   20 однотипных impl'ов, список меняется раз в месяц → x-макрос
//   сотни структур из бинарного лога            → build.rs + include!
//   3 варианта одной логики                     → generic fn
//   однотипный код, повторённый 3 раза          → обычная функция
//                                                  (или терпкий цикл)

fn part_14_2() {
    harness::part("14.2", "ПРИМЕР: экспорт, $crate, include!");

    // --- $crate: путь, который работает и внутри, и снаружи макроса ---------
    // Внутри крейта-объявления `crate` = этот крейт, снаружи = крейт
    // пользователя. `$crate` — «тот крейт, где макрос ОБЪЯВЛЕН».
    // Если использовать просто `crate::`, то при использовании макроса
    // из другого крейта путь будет указывать не туда. Это редкая, но
    // реальная ошибка в больших проектах.
    println!("  $crate нужен, чтобы путь внутри макроса не зависел от вызывающего");
    println!("  value = {}", local_macro::exported());

    // --- include! — текстовая подстановка файла ----------------------------
    // include! принимает путь, который должен быть литералом или
    // раскрытием env!. Файл вставляется как есть, в текущее место.
    #[cfg(feature = "hot-reload")]
    println!("  include!(concat!(env!(\"OUT_DIR\"), \"/generated.rs\")) — см. задание 10.2");
    #[cfg(not(feature = "hot-reload"))]
    println!("  include! в этом модуле не используется: см. задание 10.2");

    // --- Порядок развёртывания — иллюстрация -------------------------------
    println!("\n  порядок макросов в файле = порядок их развёртывания");
    println!("  поэтому `fn` можно звать выше по файлу, а макрос — нет");
}

/// Модуль, который «экспортирует» макрос через #[macro_export].
mod local_macro {
    /// Макрос виден ТОЛЬКО в своём крейте после объявления.
    macro_rules! inner {
        ($v:expr) => {
            $v + 1
        };
    }

    pub fn exported() -> i32 {
        inner!(41)
    }

    // Если раскомментировать, ошибка «cannot find macro» в другом
    // крейте: локальный макрос не экспортируется.
    // #[macro_export]
    // macro_rules! visible_everywhere { () => {}; }
}

