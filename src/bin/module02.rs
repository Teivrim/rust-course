fn part_2_1() {
    harness::part("2.1", "ПРИМЕР: чтение, запись и split borrows");

    let mut verts = vec![3.0f32, 4.0, 5.0, 0.0, 0.0, 0.0];
    println!("  до:  {verts:?}");

    // --- Неизменяемое заимствование: сколько угодно разных &T --------------
    let len = verts.len(); // чтение без заема, len — usize (Copy)
    let head: &[f32] = &verts[..3];
    let tail: &[f32] = &verts[3..];
    println!("  много &T одновременно: len={len}, head={head:?}, tail={tail:?}");

    // --- Изменяемое заимствование: ровно одно ------------------------------
    normalize_in_place(&mut verts);
    println!("  после normalize_in_place: {verts:?}");

    // --- split_at_mut: два &mut на один слайс -------------------------------
    // Компилятор ЗНАЕТ, что эти два куска не пересекаются, и разрешает
    // оба. В C++ пришлось бы вручную проверять индексы.
    let mut data = [1u8, 2, 3, 4, 5, 6];
    {
        let (a, b) = data.split_at_mut(3);
        a[0] = 99;
        b[0] += 100;
    }
    println!("  split_at_mut: {data:?}  (правый кусок сдвинут на +100)");

    // --- ⛔ ЗАПРЕЩЕНО: &mut и & на одном значении ---------------------------
    // let r = &verts;            // заём
    // let w = &mut verts;         // ⛔ E0502: cannot borrow as mutable
    //                            //    because it is also borrowed as immutable

    // --- ⛔ ЗАПРЕЩЕНО: push с живым & ---------------------------------------
    // let first = &verts[0];
    // verts.push(1.0);            // ⛔ E0502: push требует &mut Vec,
    //                            //    а first жив (используется ниже)
    // println!("{first}");

    // --- ТРИ ФОРМЫ ЦИКЛА: они НЕ взаимозаменяемы ---------------------------
    let mut v = vec![1, 2, 3];
    for x in &v {
        println!("  for x in &v      -> x = {x} (x: &i32, v остаётся нашей)");
    }
    for x in &mut v {
        *x *= 10;
    }
    println!("  for x in &mut v  -> v изменён: {v:?}");
    for x in v {
        println!("  for x in v       -> x = {x} (v СЪЕДЕНА, цикл её забрал)");
    }
    // println!("{v:?}");  // ⛔ v больше не существует
    //   Сравни с C++: `for (auto x : v)` крадёт копию, `for (auto& x : v)` — ссылку.
    //   В Rust «красть или не красть» — часть типа на каждом шаге цикла.
}

/// Нормализует первые три компонента как вектор (нормуляция нормали).
/// Меня данные НА МЕСТЕ, без аллокации — ради этого и нужны заимствования.
fn normalize_in_place(v: &mut [f32]) {
    if v.len() < 3 {
        return;
    }
    let len = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    if len > f32::EPSILON {
        v[0] /= len;
        v[1] /= len;
        v[2] /= len;
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТЬ 2.2 — ТЕОРИЯ: reborrow и эллизия
// ─────────────────────────────────────────────────────────────────────────────
//
// REBORROW: когда ты передаёшь `&mut T` в функцию, которая ждёт `&mut T`,
// Rust тайно создаёт «заём на заём» и **не** переводит исходную
// ссылку в «использованную». Исходный `&mut` остаётся твоим. Поэтому
//
// ```ignore
// let mut v = vec![1];
// let w = &mut v;
// grow(w);      // reborrow
// grow(w);      // снова reborrow — w всё ещё можно использовать
// println!("{v:?}");  // ок!
// ```
//
// ЭЛИЗИЯ (lifetime elision) — правила, по которым компилятор сам
// подставляет времена жизни, чтобы не писать `<'a>` везде:
//
//   П1. У каждого ПАРАМЕТРА-ССЫЛКИ свой lifetime.
//   П2. Если параметров-ссылок ровно один — он же и результат.
//   П3. Если параметров-ссылок несколько, но только один из них `&self` /
//       `&mut self` — время жизни self идёт в результат. Остальные
//       получают независимые lifetime.
//
// Три функции с одинаковой сигнатурой, но разной эллизией:
//
// ```ignore
// fn f1(s: &str) -> &str            // П2: единственная ссылка
// fn f2(a: &str, b: &str) -> &str   // П1: НЕЛЬЗЯ эллизировать -> нужно писать
// fn f3(s: &self) -> &str           // П3: время жизни self
// ```
//
// `f2` без явных lifetime не компилируется — компилятор не угадывает,
// какую из двух строк вернуть. Это не занудство, это защита от dangling.

fn part_2_2() {
    harness::part("2.2", "ПРИМЕР: reborrow, эллизия, NLL");

    // --- Reborrow -----------------------------------------------------------
    let mut v = vec![1u32];
    let w = &mut v;
    grow(w);
    grow(w); // w всё ещё валиден — это reborrow, а не перемещение
    println!("  reborrow: {v:?} (w можно было использовать снова)");

    // --- Эллизия: П2 — один параметр-ссылка --------------------------------
    let owned = String::from("первую");
    let borrowed = String::from("вторую");
    let r = longer(&owned, &borrowed);
    println!("  f(&self, &str) -> &str: {r:?}");

    // --- Эллизия: П1 — два параметра, нужно имя -----------------------------
    let r2 = longer_explicit(&owned, &borrowed);
    println!("  f<'a>(&'a, &'a) -> &'a: {r2:?}");

    // --- NLL: заём умер по последнему использованию -------------------------
    let mut data = vec![10, 20, 30];
    {
        let first = &data[0];
        println!("  NLL: читаем data[0] = {first}");
        // заём `first` умер здесь. Ниже `data` снова свободна:
    }
    data.push(40);
    println!("  NLL: push после смерти займа: {data:?}");

    // --- NLL НЕ спасает, если ссылка ещё нужна -----------------------------
    // let first = &data[0];
    // data.push(50);          // ⛔ E0502, пока `first` используется ниже
    // println!("{first}");
    // println!("{data:?}");

    // --- ⛔ Возврат ссылки на локалку (dangling в C++) ----------------------
    // fn bad() -> &i32 { let x = 42; &x }   // ⛔ E0515: returns a reference
    //                                        //     to local variable `x`
    // В C++ это сработало бы и вернуло мусор из стека. Это та же ошибка,
    // но в C++ она «работает, пока не напишешь -O2».

    let val = 42;
    println!("  вместо этого: взять владение — fn own() -> i32 {{ let x = 42; x }}");
    assert_eq!(own(), val);
}

fn grow(v: &mut Vec<u32>) {
    v.push(v.len() as u32 + 100);
}

// П2: единственная ссылка — эллизия работает.
fn longer<'a>(a: &'a str, b: &'a str) -> &'a str {
    if a.len() >= b.len() { a } else { b }
}

// То же самое, но лайфтайм назван явно. Читай как документацию:
// «результат живёт не дольше самой короткой из входных строк».
fn longer_explicit<'a>(a: &'a str, b: &'a str) -> &'a str {
    longer(a, b)
}

fn own() -> i32 {
    let x = 42;
    x
}

// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТЬ 2.3 — ТЕОРИЯ: три способа сломать обход
// ─────────────────────────────────────────────────────────────────────────────
//
// Реальная задача: обойти `Vec`, попутно его меняя. В C++ ты бы начал с
// `for (auto it = v.begin(); ...)`. В Rust так нельзя, и вот почему.
//
// СПОСОБ 1 — счётчик индекса. Работает всегда. Именно так делают в
//   горячих циклах, когда нужна индексация и предсказуемость:
//
//   for i in 0..v.len() { v.swap(i, j); }   // ок: индексация, не итератор
//
// СПОСОБ 2 — забрать владение через `for v in vec`. Работает, но
//   структура съедена.
//
// СПОСОБ 3 — `drain` / `retain` / `extract_if`: библиотека сама решает
//   проблему, потому что внутри неё живёт `unsafe`-код, доказывающий
//   безопасность. Тебе дан безопасный API со сложной внутренностью —
//   в этом и сила языка: не весь код обязан быть без `unsafe`, но
//   **прикладной** код может.
//
// ЧАСТЫЙ ПРОМАХ: `.iter_mut()` + `push` в том же цикле. Нельзя: живёт
//   `&mut` от `iter_mut`. Лечится через `mem::take` + возврат.

fn part_2_3() {
    harness::part("2.3", "ПРИМЕР: обход с изменением тремя способами");

    // --- Способ 1: индексы --------------------------------------------------
    let mut v = vec![5, 3, 9, 1, 7];
    for i in 0..v.len() {
        for j in i + 1..v.len() {
            if v[j] < v[i] {
                v.swap(i, j); // swap, а не присваивание через temp
            }
        }
    }
    println!("  1) индексы + swap:            {v:?}");

    // --- Способ 2: владение -------------------------------------------------
    let mut owned = vec![5, 3, 9, 1, 7];
    for x in &mut owned {
        *x *= 2;
    }
    println!("  2) &mut в цикле:              {owned:?}");

    // --- Способ 3: retain — библиотека решает проблему за тебя -------------
    let mut keep = vec![1, 2, 3, 4, 5, 6, 7, 8];
    let removed: Vec<i32> = keep.iter().copied().filter(|x| x % 2 == 0).collect();
    keep.retain(|x| x % 2 != 0);
    println!("  3) retain: осталось {keep:?}, убрано {removed:?}");

    // --- ⛔ То, что не компилируется ----------------------------------------
    // let mut v = vec![1, 2, 3];
    // for x in v.iter_mut() { v.push(*x); }  // ⛔ E0499: two mutable borrows
    //
    // ПРАВИЛЬНЫЙ рецепт с mem::take:
    let mut w = vec![1, 2, 3];
    let mut moved = std::mem::take(&mut w); // w теперь пуст, заём снят
    for x in &mut moved {
        w.push(*x * 10); // w свободен — заём живёт на `moved`, а не на `w`
    }
    moved.clear();
    println!("  mem::take + push:             {w:?}");
}

