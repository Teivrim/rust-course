//! ЧАСТЬ 2.1 — ТЕОРИЯ
//! ─────────────────────────────────────────────────────────────────────────────
//! ЧАСТЬ 1 научила владению. Владение — это слишком строго: чтобы дать
//! функции прочитать `Vec`, пришлось бы отдать его целиком. Rust решает это
//! заимствованием: временно дать доступ, не забирая владение.
//!
//! ТРИ ФОРМЫ ВЛАДЕНИЯ/ДОСТУПА (сравни с C++):
//!
//!   T        — владение. C++: `T` (или `auto`+move). В Rust переменная
//!              «съедает» значение при `=` или передаче в функцию.
//!   &T       — неизменяемое заимствование. C++: `const T&`. Плюс Rust
//!              гарантирует, что объект жив, пока есть ссылка.
//!   &mut T   — изменяемое заимствование. C++: `T&`. Rust дополнительно
//!              запрещает использовать исходную переменную, пока жив `&mut`.
//!
//! ПРАВИЛО ДВУХ ЗАЙМОВ (the borrow checker, целиком):
//!   1. В любой момент у значения может быть либо МНОГО `&T`, либо ОДИН `&mut T`.
//!      Никогда — одно и то же.
//!   2. Ссылка должна жить не дольше, чем значение, на которое указывает.
//!
//! СМЫСЛ ПРАВИЛА 1. Правило существует не из вкуса, а ради двух гарантий:
//!   (a) **Нет гонок данных.** Если два потока держат `&T`, они не могут
//!       писать. В C++ `const T&` из другого потока — это гонка, если
//!       кто-то пишет из третьего.
//!   (b) **Нет инвалидации через алиасы.** Один `&mut Vec` и один `&Vec`
//!       одновременно невозможны, поэтому `push` не может инвалидировать
//!       ссылку, которую кто-то ещё держит.
//!
//! ЧТО ЭТО ЗАПРЕЩАЕТ (сравни с C++, где всё это «просто работает»):
//!   * итерировать `Vec`, держа `push` на том же Vec (инвалидация итератора);
//!   * вернуть `&T` на локальную переменную (в C++ — dangling pointer);
//!   * положить `&mut` в структуру и тут же забыть про неё.
//!
//! NLL (non-lexical lifetimes): заем заканчивается **последним
//! использованием**, а не концом блока. Поэтому
//!
//! ```ignore
//! let mut v = vec![1, 2, 3];
//! let first = &v[0];      // заём начался
//! println!("{first}");    // заём закончился ЗДЕСЬ
//! v.push(4);              // ⛔ нет! v[0] снова нужен ниже? нет — поэтому ОК
//! ```
//!
//! работает, если `first` больше не используется. Это то, к чему придёшь
//! в модуле 03 как к «временам жизни», а пока просто запомни: Rust
//! смотрит на данные, а не на фигурные скобки.

